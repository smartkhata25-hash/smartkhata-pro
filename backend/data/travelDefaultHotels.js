const normalizeText = (value = "") =>
  String(value || "")
    .replace(/\s+/g, " ")
    .trim();

const normalizeHotel = (hotel = {}) => ({
  name: normalizeText(hotel.name),
  city: normalizeText(hotel.city),
  country: normalizeText(hotel.country || "Saudi Arabia"),
  starRating:
    Number.isInteger(Number(hotel.starRating)) &&
    Number(hotel.starRating) >= 1 &&
    Number(hotel.starRating) <= 5
      ? Number(hotel.starRating)
      : null,
  vendorId: null,
  distanceText: normalizeText(hotel.distanceText),
  defaultRate: Math.max(Number(hotel.defaultRate) || 0, 0),
  currency: String(hotel.currency || "SAR")
    .trim()
    .toUpperCase(),
  address: normalizeText(hotel.address),
  contact: normalizeText(hotel.contact),
  notes: normalizeText(hotel.notes),
  isActive: hotel.isActive !== false,
});

const seenHotels = new Set();

const travelDefaultHotels = DEFAULT_TRAVEL_HOTELS.map(normalizeHotel).filter(
  (hotel) => {
    if (!hotel.name || !hotel.city) {
      return false;
    }

    const key = `${hotel.name.toLowerCase()}::${hotel.city.toLowerCase()}`;

    if (seenHotels.has(key)) {
      return false;
    }

    seenHotels.add(key);

    return true;
  },
);

module.exports = travelDefaultHotels;
